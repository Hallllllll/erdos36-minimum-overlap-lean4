#!/usr/bin/env bash
set -euo pipefail

ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)"
cd "$ROOT"

MODE=write
if [[ ${1:-} == --check ]]; then
  MODE=check
  shift
fi
if [[ $# -ne 1 ]]; then
  printf 'usage: %s [--check] benchmarks/results/linux-RUN_ID\n' "$0" >&2
  exit 2
fi

RUN_DIR="${1%/}"
RUN_ID="${RUN_DIR##*/}"
RUN_ID="${RUN_ID#linux-}"
MEASUREMENTS="$RUN_DIR/measurements.tsv"
PAIRS="$RUN_DIR/pair_summary.tsv"
REPOSITORY_VALIDATION="paper/validation"
REPOSITORY_FIGURES="paper/figures"
VALIDATION="$REPOSITORY_VALIDATION"
FIGURES="$REPOSITORY_FIGURES"
CHECK_TMP=""
if [[ "$MODE" == check ]]; then
  CHECK_TMP="$(mktemp -d "${TMPDIR:-/tmp}/overlap-plot-check.XXXXXX")"
  trap 'rm -rf -- "$CHECK_TMP"' EXIT
  VALIDATION="$CHECK_TMP/validation"
  FIGURES="$CHECK_TMP/figures"
fi

for input in "$MEASUREMENTS" "$PAIRS"; do
  if [[ ! -f "$input" ]]; then
    printf 'missing benchmark input: %s\n' "$input" >&2
    exit 2
  fi
done

mkdir -p "$VALIDATION" "$FIGURES"
cp "$PAIRS" "$VALIDATION/linux-scaling.tsv"

write_series() {
  local mode="$1"
  local phase="$2"
  local output="$3"
  local title="$4"
  {
    printf '%% %s; generated from %s/measurements.tsv\n' "$title" "$RUN_DIR"
    printf 'cells\tseconds\tmax_rss_kib\n'
    awk -F '\t' -v mode="$mode" -v phase="$phase" '
      NR > 1 && $4 == mode && $2 == phase && $5 == "pass" {
        print $3 "\t" $7 "\t" $11
      }
    ' "$MEASUREMENTS" | sort -n
  } > "$output"
}

write_series direct elaboration \
  "$VALIDATION/linux-direct-elaboration.dat" "direct elaboration"
write_series packed elaboration \
  "$VALIDATION/linux-packed-elaboration.dat" "packed elaboration"
write_series direct leanchecker \
  "$VALIDATION/linux-direct-replay.dat" "direct kernel replay"
write_series packed leanchecker \
  "$VALIDATION/linux-packed-replay.dat" "packed kernel replay"

{
  printf '%% failures; generated from %s/measurements.tsv\n' "$RUN_DIR"
  printf 'cells\tphase\tmode\tseconds\tstatus\n'
  awk -F '\t' '
    NR > 1 && $5 != "pass" {
      print $3 "\t" $2 "\t" $4 "\t" $7 "\t" $5
    }
  ' "$MEASUREMENTS" | sort -n -k1,1
} > "$VALIDATION/linux-failures.dat"

{
  printf '%% censored wall-cap observations; generated from %s/measurements.tsv\n' \
    "$RUN_DIR"
  printf 'cells\tseconds\tstatus\n'
  awk -F '\t' '
    NR > 1 && $5 == "timeout" {
      print $3 "\t" $7 "\ttimeout"
    }
  ' "$MEASUREMENTS" | sort -n
} > "$VALIDATION/linux-censored.dat"

cat > "$FIGURES/linux-scaling.tex" <<EOF
% Generated by benchmarks/linux/render_plot.sh. Do not edit by hand.
% Source: $RUN_DIR/measurements.tsv
\begin{figure*}[t]
  \centering
  \begin{tikzpicture}
    \begin{axis}[
      width=0.94\textwidth,
      height=6.3cm,
      xmode=log,
      ymode=log,
      log basis x=2,
      xlabel={cells in the nondegenerate certificate slice},
      ylabel={wall seconds, including process startup},
      xtick={128,256,512,1024,2048},
      xticklabels={128,256,512,1024,2048},
      grid=major,
      legend columns=2,
      legend style={at={(0.5,1.03)},anchor=south},
    ]
      \addplot+[mark=*] table[x=cells,y=seconds]
        {validation/linux-direct-elaboration.dat};
      \addlegendentry{direct elaboration}
      \addplot+[mark=square*] table[x=cells,y=seconds]
        {validation/linux-packed-elaboration.dat};
      \addlegendentry{packed elaboration}
      \addplot+[mark=triangle*] table[x=cells,y=seconds]
        {validation/linux-direct-replay.dat};
      \addlegendentry{direct replay}
      \addplot+[mark=diamond*] table[x=cells,y=seconds]
        {validation/linux-packed-replay.dat};
      \addlegendentry{packed replay}
      \addplot+[only marks, mark=x, mark size=3pt, black]
        table[x=cells,y=seconds] {validation/linux-censored.dat};
      \addlegendentry{Direct timeout (censored)}
    \end{axis}
  \end{tikzpicture}
  \caption{Paired direct-sum and packed-product certificate checks on a Linux
  worker. Each point is one fresh process; generation, elaboration, and
  kernel replay are measured separately under identical 600-second and
  16~GiB per-process caps. Direct elaboration timed out at 1,024 cells.
  Direct replay at 1,024 cells and both Direct phases at 2,048 cells were
  not run. The cross marks the observed timeout at 600.03 seconds.}
  \label{fig:linux-scaling}
  \Description{A log-log line chart compares direct and packed certificate
  elaboration and replay across 128, 256, 512, 1024, and 2048 cells. It
  marks the 1024-cell direct elaboration timeout and states that later
  direct phases were not run.}
\end{figure*}
EOF

if [[ "$MODE" == check ]]; then
  stale=0
  for relative in \
    validation/linux-scaling.tsv \
    validation/linux-direct-elaboration.dat \
    validation/linux-packed-elaboration.dat \
    validation/linux-direct-replay.dat \
    validation/linux-packed-replay.dat \
    validation/linux-failures.dat \
    validation/linux-censored.dat \
    figures/linux-scaling.tex; do
    if ! cmp -s "$CHECK_TMP/$relative" "$ROOT/paper/$relative"; then
      printf 'stale or missing: paper/%s\n' "$relative" >&2
      stale=1
    fi
  done
  if (( stale )); then
    exit 1
  fi
  printf 'verified Linux scaling data and PGFPlots source from %s\n' "$RUN_DIR"
else
  printf 'rendered %s and %s/linux-scaling.tex\n' \
    "$VALIDATION" "$FIGURES"
fi
