#!/usr/bin/env python3
"""Generate the benchmark table and timing figure from completed measurements."""

from __future__ import annotations

import argparse
import json
import math
import sys
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESULTS = ROOT / "benchmarks" / "results"
TABLE_PATH = ROOT / "paper" / "generated" / "bench_table.tex"
TIMING_PATH = ROOT / "paper" / "figures" / "timing.tex"

CORE_MODULES = [
    "Tree",
    "Data",
    "Numerical",
    "Algebra",
    "AffineBridge",
    "Profile",
    "Spec",
    "Main",
]
CHART_MODULES = [*CORE_MODULES, "Bench"]

EXPECTED_OPERATIONS = {
    ("clean", "project"),
    *(("build", module) for module in CORE_MODULES),
    ("build", "Bench"),
    ("clean", "project-before-default-build"),
    ("default_build", "Overlap"),
    ("build_after_default", "Bench"),
    *(("leanchecker", module) for module in CORE_MODULES),
    ("leanchecker", "Bench"),
}

PHASE_ORDER = [
    ("clean", "Clean"),
    ("build", "Module builds"),
    ("default_build", "Default build"),
    ("build_after_default", "Post-build"),
    ("leanchecker", "Kernel replay"),
]


class FigureError(ValueError):
    """Raised when a benchmark run is missing or inconsistent."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise FigureError(message)


def load_rows(run_dir: Path, require_complete: bool) -> list[dict]:
    measurements = run_dir / "measurements.jsonl"
    require(measurements.is_file(), f"missing measurements: {measurements}")
    rows = []
    for line_number, line in enumerate(
        measurements.read_text(encoding="utf-8").splitlines(), start=1
    ):
        if not line.strip():
            continue
        row = json.loads(line)
        if row.get("kind") == "environment":
            continue
        required = {
            "phase",
            "unit",
            "wall_seconds",
            "peak_rss_bytes",
            "exit_status",
            "raw_log",
        }
        missing = required.difference(row)
        require(not missing, f"{measurements}:{line_number}: missing {sorted(missing)}")
        require(
            (run_dir / row["raw_log"]).is_file(),
            f"{measurements}:{line_number}: missing raw log {row['raw_log']}",
        )
        rows.append(row)

    keys = [(row["phase"], row["unit"]) for row in rows]
    duplicates = [key for key, count in Counter(keys).items() if count > 1]
    require(not duplicates, f"duplicate measurements: {duplicates}")
    if require_complete:
        present = set(keys)
        missing = sorted(EXPECTED_OPERATIONS.difference(present))
        require(not missing, f"incomplete benchmark run; missing {missing}")
        failures = [
            f"{row['phase']}/{row['unit']}={row['exit_status']}"
            for row in rows
            if (row["phase"], row["unit"]) in EXPECTED_OPERATIONS
            and row["exit_status"] != 0
        ]
        require(not failures, f"benchmark run contains failures: {failures}")
    return rows


def select_run(results: Path) -> Path:
    candidates = sorted(
        (
            path
            for path in results.iterdir()
            if path.is_dir() and (path / "measurements.jsonl").is_file()
        ),
        key=lambda path: path.name,
        reverse=True,
    )
    failures = []
    for candidate in candidates:
        try:
            load_rows(candidate, require_complete=True)
        except (FigureError, json.JSONDecodeError) as error:
            failures.append(f"{candidate.name}: {error}")
            continue
        return candidate
    detail = "\n".join(failures) if failures else "no measurement files found"
    raise FigureError(f"no complete benchmark run is available\n{detail}")


def phase_rows(rows: list[dict]) -> list[dict]:
    output = []
    for phase, label in PHASE_ORDER:
        selected = [row for row in rows if row["phase"] == phase]
        require(selected, f"no rows for phase {phase}")
        output.append(
            {
                "phase": phase,
                "label": label,
                "count": len(selected),
                "wall_seconds": sum(float(row["wall_seconds"]) for row in selected),
                "peak_rss_mib": max(int(row["peak_rss_bytes"]) for row in selected)
                / (1024 * 1024),
            }
        )
    return output


def render_table(rows: list[dict], run_dir: Path) -> str:
    phases = phase_rows(rows)
    total_wall = sum(row["wall_seconds"] for row in phases)
    total_rss = max(row["peak_rss_mib"] for row in phases)
    lines = [
        "% Generated by paper/generate_figures.py. Do not edit by hand.",
        "% Source: benchmarks/results/" + run_dir.name + "/measurements.jsonl",
        r"\begin{table*}[t]",
        r"  \centering",
        r"  \caption{Selected Lean command phases from one canonical run. Each",
        r"  command contributes one wall-time and one peak-RSS observation;",
        r"  all 22 commands exited successfully.}",
        r"  \label{tab:benchmark}",
        r"  \small",
        r"  \begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrr@{}}",
        r"    \hline",
        r"    Phase & Commands & Wall (s) & Max RSS (MiB) & Status \\",
        r"    \hline",
    ]
    for phase in phases:
        lines.append(
            f"    {phase['label']} & {phase['count']} & "
            f"{phase['wall_seconds']:.3f} & {phase['peak_rss_mib']:.1f} & pass \\\\"
        )
    lines.extend(
        [
            r"    \hline",
            f"    Total & {len(rows)} & {total_wall:.3f} & {total_rss:.1f} & pass \\\\",
            r"    \hline",
            r"  \end{tabular*}",
            r"  \Description{A five-row benchmark summary table. It reports",
            r"  command counts, cumulative wall time, and maximum resident memory",
            r"  for cleaning, module construction, the default build, the",
            r"  post-default benchmark build, and fresh-process kernel replay.}",
            r"\end{table*}",
        ]
    )
    return "\n".join(lines) + "\n"


def nice_ticks(maximum: float) -> list[float]:
    if maximum <= 0:
        return [0.0, 1.0]
    rough = maximum / 4
    magnitude = 10 ** math.floor(math.log10(rough))
    scaled = rough / magnitude
    factor = 1 if scaled <= 1 else 2 if scaled <= 2 else 5 if scaled <= 5 else 10
    step = factor * magnitude
    count = math.ceil(maximum / step)
    return [index * step for index in range(count + 1)]


def render_timing(rows: list[dict], run_dir: Path) -> str:
    by_key = {(row["phase"], row["unit"]): row for row in rows}
    quantities = []
    for module in CHART_MODULES:
        build = by_key.get(("build", module)) or by_key.get(
            ("build_after_default", module)
        )
        replay = by_key[("leanchecker", module)]
        require(build is not None, f"no build timing for {module}")
        quantities.extend([float(build["wall_seconds"]), float(replay["wall_seconds"])])

    maximum = max(quantities)
    ticks = nice_ticks(maximum)
    plot_width_cm = 8.1
    unit_cm = plot_width_cm / (ticks[-1] or maximum)
    group_height = 0.86
    top = len(CHART_MODULES) * group_height
    axis_bottom = -0.35
    lines = [
        "% Generated by paper/generate_figures.py. Do not edit by hand.",
        "% Source: benchmarks/results/" + run_dir.name + "/measurements.jsonl",
        r"\begin{figure*}[t]",
        r"  \centering",
        r"  \begin{tikzpicture}[x=1cm,y=1cm,font=\scriptsize]",
    ]
    for tick in ticks:
        x = tick * unit_cm
        lines.append(
            rf"    \draw[black!20] ({x:.3f},{axis_bottom:.3f}) -- "
            rf"({x:.3f},{top + 0.15:.3f});"
        )
        lines.append(
            rf"    \node[anchor=north] at ({x:.3f},{axis_bottom - 0.08:.3f}) "
            rf"{{{tick:g}}};"
        )
    lines.extend(
        [
            rf"    \draw[->] (0,{axis_bottom:.3f}) -- "
            rf"({plot_width_cm + 0.2:.3f},{axis_bottom:.3f});",
            rf"    \node[anchor=west] at ({plot_width_cm + 0.02:.3f},"
            rf"{axis_bottom - 0.08:.3f}) {{seconds}};",
            rf"    \fill[black!65] (-0.15,{top + 0.58:.3f}) rectangle "
            rf"(-0.02,{top + 0.74:.3f});",
            rf"    \node[anchor=west] at (0.03,{top + 0.66:.3f}) {{module build}};",
            rf"    \fill[black!25] (2.35,{top + 0.58:.3f}) rectangle "
            rf"(2.48,{top + 0.74:.3f});",
            rf"    \node[anchor=west] at (2.53,{top + 0.66:.3f}) {{fresh kernel replay}};",
        ]
    )

    for index, module in enumerate(CHART_MODULES):
        center = top - index * group_height
        build = by_key.get(("build", module)) or by_key.get(
            ("build_after_default", module)
        )
        replay = by_key[("leanchecker", module)]
        build_seconds = float(build["wall_seconds"])
        replay_seconds = float(replay["wall_seconds"])
        build_x = build_seconds * unit_cm
        replay_x = replay_seconds * unit_cm
        lines.append(
            rf"    \node[anchor=east] at (-0.12,{center:.3f}) {{{module}}};"
        )
        lines.append(
            rf"    \fill[black!65] (0,{center + 0.05:.3f}) rectangle "
            rf"({build_x:.3f},{center + 0.31:.3f});"
        )
        lines.append(
            rf"    \node[font=\tiny,anchor=west] at ({build_x + 0.05:.3f},"
            rf"{center + 0.18:.3f}) {{{build_seconds:.2f}}};"
        )
        lines.append(
            rf"    \fill[black!25] (0,{center - 0.31:.3f}) rectangle "
            rf"({replay_x:.3f},{center - 0.05:.3f});"
        )
        lines.append(
            rf"    \node[font=\tiny,anchor=west] at ({replay_x + 0.05:.3f},"
            rf"{center - 0.18:.3f}) {{{replay_seconds:.2f}}};"
        )

    lines.extend(
        [
            r"  \end{tikzpicture}",
            r"  \caption{Wall times for distinct ordinary construction and",
            r"  fresh-process kernel-replay commands. Each bar is one observed",
            r"  command. The table aggregates those same commands by phase.}",
            r"  \label{fig:timing}",
            r"  \Description{A horizontal grouped bar chart. Eight rows correspond",
            r"  to the core proof modules and a ninth to the benchmark module;",
            r"  each row shows one module-build time and one fresh-process kernel",
            r"  replay time in seconds.}",
            r"\end{figure*}",
        ]
    )
    return "\n".join(lines) + "\n"


def write_if_changed(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8", newline="\n")
    temporary.replace(path)


def generate(
    results: Path = DEFAULT_RESULTS, run_dir: Path | None = None, check: bool = False
) -> Path:
    selected = run_dir.resolve() if run_dir is not None else select_run(results)
    rows = [
        row
        for row in load_rows(selected, require_complete=True)
        if (row["phase"], row["unit"]) in EXPECTED_OPERATIONS
    ]
    outputs = {
        TABLE_PATH: render_table(rows, selected),
        TIMING_PATH: render_timing(rows, selected),
    }
    if check:
        stale = [
            path
            for path, text in outputs.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            names = ", ".join(str(path.relative_to(ROOT)) for path in stale)
            raise FigureError(f"generated benchmark figures are stale: {names}")
    else:
        for path, text in outputs.items():
            write_if_changed(path, text)
    return selected


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results",
        type=Path,
        default=DEFAULT_RESULTS,
        help="benchmark results directory",
    )
    parser.add_argument(
        "--run-dir",
        dest="run_dir",
        type=Path,
        help="explicit benchmark run directory; must be complete",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify generated benchmark artifacts without writing",
    )
    args = parser.parse_args(argv)
    try:
        selected = generate(args.results, args.run_dir, args.check)
    except (FigureError, json.JSONDecodeError, OSError) as error:
        print(f"figure error: {error}", file=sys.stderr)
        return 1
    action = "verified" if args.check else "generated"
    print(f"{action} benchmark artifacts from {selected.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
